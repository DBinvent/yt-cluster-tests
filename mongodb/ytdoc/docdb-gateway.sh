#!/bin/bash
# ytperf-ytdoc: DocumentDB's gateway - the MongoDB wire protocol on DOCDB_PORT (default
# 10260) - once the server answers and DocumentDB's extension is in DOCDB_DB (run.sh
# creates it), and again 5 s after it exits. Plain and TLS connections alike (no
# EnforceTls), a certificate it makes itself.
set -uo pipefail
db="${DOCDB_DB:-docdb}"
port="${DOCDB_PORT:-10260}"
conf=/tmp/docdb-gateway.json
cat > "$conf" <<EOF
{
  "NodeHostName": "localhost",
  "BlockedRolePrefixes": ["documentdb", "citus", "pg", "internal_role"],
  "PostgresSystemUser": "postgres",
  "PostgresHostName": "127.0.0.1",
  "PostgresPort": ${PGPORT:-5432},
  "PostgresDatabase": "$db",
  "GatewayListenPort": $port,
  "EnforceTls": false,
  "CertificateOptions": { "CertType": "PemAutoGenerated" }
}
EOF
until psql -h 127.0.0.1 -U postgres -d "$db" -qAtc "select 1 from pg_extension where extname = 'documentdb'" 2>/dev/null | grep -q 1; do
	sleep 2
done
echo "[docdb] gateway on :$port, database $db"
while :; do
	documentdb_gateway "$conf"
	echo "[docdb] gateway exited ($?) - again in 5 s"
	sleep 5
done
